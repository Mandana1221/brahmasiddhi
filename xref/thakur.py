"""NV（ヴァールッティカ）対訳ページのスートラ番号を Thakur 版の番号に直す。

NV 対訳の一部のページはヒンディー訳（Śrīnivāsa Śāstrī）の番号で数えている。各ページの注記によれば
  * 2.1：ヒンディー訳の 2.1.33（न चैकदेशोपलब्धिः…）は Thakur 版ではスートラでない（バーシュヤの文）。
         ヒンディー訳の 2.1.34–69 は Thakur 版の 2.1.33–68。
  * 3.1：ヒンディー訳は Vārttika が引くヴァイシェーシカ・スートラを 3.1.38 と数えるので、
         ヒンディー訳の 3.1.39–73 は Thakur 版の 3.1.38–72。
2.2 などそのほかの章は両者が一致する。NVTT・NVTP 全訳は Thakur 版の番号による。
"""
import re

# ヒンディー訳の番号で数えているページ（他のページは Thakur 版・通行の番号）
HINDI_PAGES = {15, 16, 17, 18, 19, 20, 21, 22, 32, 33, 34, 35}
DEV = str.maketrans('0123456789', '०१२३४५६७८९')
LAT = str.maketrans('०१२३४५६७८९', '0123456789')


def h2t(a, b, c):
    """ヒンディー訳の番号 → Thakur 版の番号（文字列）。スートラでないものは '2.1.32付'。"""
    a, b, c = int(a), int(b), int(c)
    if (a, b) == (2, 1):
        if c == 33:
            return '2.1.32付'
        if c >= 34:
            c -= 1
    elif (a, b) == (3, 1) and c >= 39:
        c -= 1
    return f'{a}.{b}.{c}'


def conv_lat(t):
    """和文中の「2.1.34」「3.1.40–3.1.42」「3.1.35–36」をThakur 版の番号に。"""
    def one(m):
        a, b, c, sep, a2, b2, d = m.groups()
        first = h2t(a, b, c)
        if not sep:
            return first
        last = h2t(a2 or a, b2 or b, d).replace('付', '')    # 範囲の末尾が付スートラなら本スートラまで
        first = first.replace('付', '')
        if a2:
            return f'{first}{sep}{last}'
        return f'{first}{sep}{last.rsplit(".", 1)[1]}'
    return re.sub(r'(?<![\d.])([1-5])\.([12])\.(\d+)(?:([–-])(?:([1-5])\.([12])\.)?(\d+))?(?![\d.])', one, t)


def conv_dev(t):
    """原文の「॥२।१।३४॥」を Thakur 版の番号に。スートラでないものは番号を外す。"""
    def one(m):
        a, b, c = (x.translate(LAT) for x in m.groups())
        n = h2t(a, b, c)
        if n.endswith('付'):
            return '॥'
        return '॥' + '।'.join(n.split('.')).translate(DEV) + '॥'
    return re.sub(r'॥\s*([०-९]+)।([०-९]+)।([०-९]+)\s*॥', one, t)


