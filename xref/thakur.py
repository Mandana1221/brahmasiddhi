KEEP = ('\x02', '\x03')       # この間の文は番号を書き換えない


def page_no(name):
    m = re.match(r'nyayavarttika-(\d+)-taiyaku\.html$', name)
    return int(m.group(1)) if m else None


def convert_html(t, name):
    """NV 対訳ページ（または目次）の HTML を Thakur 版の番号に直す。"""
    for old, new in NOTES:
        t = t.replace(old, KEEP[0] + new + KEEP[1])
    n = page_no(name)
    if n in HINDI_PAGES or name == 'nyayavarttika-index.html':
        parts = re.split(f'({KEEP[0]}.*?{KEEP[1]})', t, flags=re.S)
        out = []
        for p in parts:
            if p.startswith(KEEP[0]):
                out.append(p)
                continue
            # タグの中（属性）は変えず、テキストだけ変える
            out.append(re.sub(r'>([^<]+)<', lambda m: '>' + conv_dev(conv_lat(m.group(1))) + '<', p))
        t = ''.join(out)
    return t.replace(KEEP[0], '').replace(KEEP[1], '')
