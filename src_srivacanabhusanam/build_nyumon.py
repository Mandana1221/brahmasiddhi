def fig(cap, body, note=None):
    n = f'\n  <div class="cap2">{note}</div>' if note else ''
    return f'<figure class="fig">\n  <figcaption>{cap}</figcaption>\n{body}{n}\n</figure>\n'
def table(head, rows):
    th = "".join(f"<th>{h}</th>" for h in head)
    tr = []
    for r in rows:
        if isinstance(r, str):
            tr.append(f'<tr class="grp"><td colspan="{len(head)}">{r}</td></tr>')
        else:
            tr.append("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>")
    return f'<div class="tscroll"><table class="t"><thead><tr>{th}</tr></thead><tbody>{"".join(tr)}</tbody></table></div>'
def flow(nodes, arrows=None):
    out = []
    for i, nd in enumerate(nodes):
        cls, inner = nd if isinstance(nd, tuple) else ("", nd)
        out.append(f'<div class="node {cls}">{inner}</div>')
        if i < len(nodes) - 1:
            lab = arrows[i] if arrows else ""
            out.append(f'<div class="arr lbl"><span class="ac">→</span><span>{lab}</span></div>' if lab else '<div class="arr"><span class="ac">→</span></div>')
    return '<div class="flow">' + "".join(out) + '</div>'
def grid(*cells, n=2):
    return f'<div class="grid{n}">' + "".join(f'<div class="node {c}">{h}</div>' for c, h in cells) + '</div>'
def I(x): return f"<i>{x}</i>"
def V(n, label=None): return f'<a class="src" href="srivacanabhusanam_kadan.html#s{n}">{label or "§" + str(n)}</a>'
def key(title, body): return f'<div class="key"><div class="lbl">{title}</div>{body}</div>\n'
def box(body): return f'<div class="card">{body}</div>\n'

